#!/usr/bin/env python3
"""Generate src/circuit_data.rs from the bacinger/f1-circuits GeoJSON.

Usage: tools/gen_circuits.py path/to/f1-circuits.geojson > src/circuit_data.rs

Get the data from https://github.com/bacinger/f1-circuits (MIT licence,
Copyright (c) 2019-2025 Tomislav Bacinger). Each outline is converted to
metres around its centre (x east, z north), keeping the dataset's first point
(the start/finish line) and its order, which follows the racing direction
except where noted in REVERSE.
"""
import json
import math
import sys

# Game name -> dataset id
CIRCUITS = [
    ("MONZA", "it-1922"), ("SPA-FRANCORCHAMPS", "be-1925"), ("MONACO", "mc-1929"),
    ("SUZUKA", "jp-1962"), ("BAHRAIN", "bh-2002"), ("COTA", "us-2012"),
    ("INTERLAGOS", "br-1940"), ("SINGAPORE", "sg-2008"), ("JEDDAH", "sa-2021"),
    ("IMOLA", "it-1953"), ("RED BULL RING", "at-1969"), ("ZANDVOORT", "nl-1948"),
    ("SHANGHAI", "cn-2004"), ("BARCELONA", "es-1991"), ("MONTREAL", "ca-1978"),
    ("HUNGARORING", "hu-1986"), ("ABU DHABI", "ae-2009"), ("LAS VEGAS", "us-2023"),
    ("QATAR", "qa-2004"), ("MIAMI", "us-2022"), ("BAKU", "az-2016"),
    ("MEXICO CITY", "mx-1962"),
]
# Outlines stored against the racing direction in the dataset
REVERSE = {"sg-2008"}


def outline(feature):
    coords = feature["geometry"]["coordinates"]
    lat0 = sum(c[1] for c in coords) / len(coords)
    pts = [(c[0] * 111320.0 * math.cos(math.radians(lat0)), c[1] * 110540.0) for c in coords]
    if math.dist(pts[0], pts[-1]) < 0.5:
        pts = pts[:-1]
    if feature["properties"]["id"] in REVERSE:
        pts = [pts[0]] + pts[1:][::-1]
    cx = sum(p[0] for p in pts) / len(pts)
    cz = sum(p[1] for p in pts) / len(pts)
    return [(p[0] - cx, p[1] - cz) for p in pts]


def main():
    data = json.load(open(sys.argv[1]))
    features = {f["properties"]["id"]: f for f in data["features"]}
    out = [
        "//! Real circuit outlines in metres around each circuit's centre (x east,",
        "//! z north), starting at the start/finish line and running in the racing",
        "//! direction. Generated by tools/gen_circuits.py from bacinger/f1-circuits",
        "//! (https://github.com/bacinger/f1-circuits), Copyright (c) 2019-2025",
        "//! Tomislav Bacinger, MIT licence.",
        "",
        "/// (game name, real length in metres, outline)",
        "pub const CIRCUITS: &[(&str, f32, &[[f32; 2]])] = &[",
    ]
    for name, cid in CIRCUITS:
        f = features[cid]
        pts = outline(f)
        body = ", ".join(f"[{x:.1f}, {z:.1f}]" for x, z in pts)
        out.append(f'    ("{name}", {f["properties"]["length"]:.1f}, &[{body}]),')
    out.append("];")
    print("\n".join(out))


if __name__ == "__main__":
    main()
